/** Looks up extra search terms for a team. This is the single seam for aliases: if CZarp adds a
 *  `team_aliases` table (alias, team_id), load it in /api/teams, put the aliases on SearchTeam,
 *  and replace this function (or pass a different `aliasesFor` to buildIndex). Nothing else changes. */
export type AliasLookup = (team: { id: number; name: string }) => string[];

export const localAliases: AliasLookup = (team) => TEAM_ALIASES[team.name] ?? [];
